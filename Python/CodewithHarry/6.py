# LISTS/ ARRAYS IN PYTHON : mutable ie new items can be included into it
l1 = [1,14,36,77,27,92,53,10]
print(l1)
l1.append(100) #adds a new item into the list
print(l1)
l1.sort()  #sorts the list
print(l1)
l1.reverse() # reverses the list
print(l1)
l1.pop(3) # pops out the item from the definite index
print(l1)